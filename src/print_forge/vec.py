"""Small 3D vector helpers on plain tuples (no numpy needed)."""

from __future__ import annotations

import math

Vec3 = tuple[float, float, float]
Vec2 = tuple[float, float]


def sub(a: Vec3, b: Vec3) -> Vec3:
    return (a[0] - b[0], a[1] - b[1], a[2] - b[2])


def add(a: Vec3, b: Vec3) -> Vec3:
    return (a[0] + b[0], a[1] + b[1], a[2] + b[2])


def scale(a: Vec3, s: float) -> Vec3:
    return (a[0] * s, a[1] * s, a[2] * s)


def dot(a: Vec3, b: Vec3) -> float:
    return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]


def cross(a: Vec3, b: Vec3) -> Vec3:
    return (
        a[1] * b[2] - a[2] * b[1],
        a[2] * b[0] - a[0] * b[2],
        a[0] * b[1] - a[1] * b[0],
    )


def length(a: Vec3) -> float:
    return math.sqrt(dot(a, a))


def normalize(a: Vec3) -> Vec3:
    n = length(a)
    if n == 0.0:
        return (0.0, 0.0, 0.0)
    return (a[0] / n, a[1] / n, a[2] / n)


def triangle_normal(a: Vec3, b: Vec3, c: Vec3) -> Vec3:
    """Unit normal by the right-hand rule (zero vector for a degenerate triangle)."""
    return normalize(cross(sub(b, a), sub(c, a)))


def triangle_area(a: Vec3, b: Vec3, c: Vec3) -> float:
    return 0.5 * length(cross(sub(b, a), sub(c, a)))
